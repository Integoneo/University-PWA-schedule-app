/**
 * changelog.ts — единственный источник истины о версиях приложения.
 *
 * Как добавить новую запись при релизе:
 *   1. Увеличь CURRENT_VERSION (semver: major.minor.patch)
 *   2. Добавь новый объект в НАЧАЛО массива changelogHistory
 *   3. При breaking changes в store — обнови DATA_VERSION в store.ts
 *
 * Типы релизов:
 *   major — ломающие изменения, новый крупный функционал
 *   minor — новые функции без ломающих изменений
 *   patch — исправления, мелкие улучшения
 *
 * description в features/fixes может содержать HTML-теги.
 */

export const CURRENT_VERSION: string = '1.1.0'
// WARN: Нужно менять вручную при выпуске версии

// ── Типы ─────────────────────────────────────────────────────────────────────

export interface ChangelogItem {
  /** Заголовок изменения. Всегда обязателен. */
  name: string
  /**
   * Подробное описание. Необязательное.
   * Поддерживает HTML: <b>, <a href="...">, <br>, <em> и т.д.
   * Рендерится через v-html — НЕ вставляй сюда пользовательский ввод.
   */
  description?: string
}

export interface ChangelogEntry {
  version: string
  /** Дата в формате YYYY-MM-DD */
  date: string
  type: 'major' | 'minor' | 'patch'
  features: ChangelogItem[]
  fixes: ChangelogItem[]
}

